  const horizons = [1, 3];
  let pendingCloses = [];
  let request, checkedAt = 0;

  function anniversary(date, months) {
    const start = new Date(date + "T00:00:00Z");
    const year = start.getUTCFullYear();
    const month = start.getUTCMonth() + months;
    const lastDay = new Date(Date.UTC(year, month + 1, 0)).getUTCDate();
    return new Date(Date.UTC(year, month, Math.min(start.getUTCDate(), lastDay))).toISOString().slice(0, 10);
  }

  function forEvent(date) {
    const targets = horizons.map(months => anniversary(date, months));
    const historical = archived[date];
    const currentBase = pendingCloses.findLast(([day]) => day < date);
    const points = historical?.every(Boolean) || !currentBase
      ? historical || []
      : [currentBase, ...targets.map(target => pendingCloses.find(([day]) => day >= target))];
    return { base: points[0], windows: targets.map((target, index) => ({
      months: horizons[index], target, point: points[index + 1],
    })) };
  }

