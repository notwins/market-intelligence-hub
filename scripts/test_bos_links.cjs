const fs=require('node:fs'),assert=require('node:assert/strict'),vm=require('node:vm');
const b=require('../site/bos-resources.js');
async function run() {
  assert.equal(b.sources.length,3);
  assert.equal(b.sources.filter(x=>x.kind==='bonds').length,2);
  assert(b.sources[2].scope.includes('no currency field'));
  assert(b.sources[1].scope.includes('including SGD'));
  assert.equal((b.cards('equities').match(/Open original PDF/g)||[]).length,1);
  assert.equal((b.cards('bonds').match(/Open original PDF/g)||[]).length,2);
  assert(b.cards().includes('previous-business-day'));
  assert(b.cards().includes('target="_blank" rel="noopener noreferrer"'));
  assert(!b.cards().includes('<iframe'));
  const html=fs.readFileSync('site/v4.html','utf8');
  for(const kind of ['equities','bonds','all'])assert(html.includes("BOSResources.cards('"+kind+"')"));
  assert(html.includes('BOSResources.refresh()'));
  for(const m of html.matchAll(/<script(?: [^>]*)?>([\s\S]*?)<\/script>/g))if(m[1].trim())new vm.Script(m[1]);
  const day='2026-11-23', prior=b.reportFor('GOOGL');
  const zip=b.sources.map(s=>({date:day,url:s.url.replace(/\d{4}-\d{2}-\d{2}/,day).replace(/\d{2}_Nov_2026/,'23_Nov_2026')}));
  const data={schemaVersion:1,documents:{equity:zip[0],bonds:zip[1],credit:zip[2]},reports:{GOOGL:prior}};
  const section={dataset:{bosResources:'bonds'}};
  global.document={querySelectorAll:()=>[section],getElementById:()=>null};
  global.fetch=async()=>({ok:true,json:async()=>data});
  await b.refresh();
  assert(section.outerHTML.includes('23 November 2026'));
  assert(b.cards('equities').includes('from 11 November 2026 universe'));
  assert.equal(b.reportFor('NVDA'),undefined);
  const saved=b.cards();
  data.reports.GOOGL={...prior,url:'javascript:alert(1)'};
  await b.refresh();assert.equal(b.cards(),saved);
  global.fetch=async()=>{throw Error('offline');};
  await b.refresh();assert.equal(b.cards(),saved);
  console.log('PASS dated source links, live refresh, report provenance and failed-refresh retention');
}
run().catch(error=>{console.error(error);process.exitCode=1;});
