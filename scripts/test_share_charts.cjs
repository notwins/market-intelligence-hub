const assert=require('node:assert/strict');
const fs=require('node:fs');
const prices=require('../site/share-prices.js');
const charts=require('../site/share-chart-workbench.js');
const snapshot=require('../site/market-snapshot.js');
const first={name:'A',points:[['2026-10-29',200],['2026-10-30',100],['2026-11-02',110],['2026-11-03',90],['2026-11-04',80]]};
const second={name:'B',points:[['2026-10-30',10],['2026-11-02',12],['2026-11-03',9]]};
const compared=charts.normalize([first,second]);
assert.equal(compared.from,'2026-10-30');assert.equal(compared.to,'2026-11-03');
for(const line of compared.lines){assert.equal(line.points[0][1],0);assert(Math.abs(line.points.at(-1)[1]+10)<1e-10);}
assert.equal(compared.lines[0].points.length,3,'same observed start and end, not unequal windows');
const six=charts.normalize(Array.from({length:6},(_,i)=>({name:'S'+i,points:second.points.map(p=>[p[0],p[1]*(i+1)])})));
assert.equal(six.lines.length,6);assert(six.lines.every(l=>l.points[0][1]===0));
assert.equal(charts.normalize([first,{name:'Missing',points:[]}]),null);
assert.equal(charts.normalize([first,{name:'No overlap',points:[['2026-11-05',10],['2026-11-06',12]]}]),null);
assert.equal(charts.normalize([first,{name:'Only one common date',points:[['2026-11-04',10]]}]),null);
const gapped=charts.normalize([first,{name:'Gaps',points:[['2026-10-30',10],['2026-11-03',12]]}]);
assert.equal(gapped.lines[1].points.length,2,'no fabricated intermediate session');
const events=[{ticker:'A',date:'2026-10-31',label:'<release>'},{ticker:'A',date:'2026-11-10',label:'Outside'}];
const svg=prices.svg(compared.lines,[],events,{percent:true,expanded:true});
assert(svg.includes('data-earnings-date="2026-10-31"'),'weekend remains actual calendar release date');
assert(!svg.includes('2026-11-10'),'outside-window event omitted');
assert(svg.includes('stroke-dasharray="2 5"'));assert(svg.includes('&lt;release&gt;'));assert(!svg.includes('NaN'));assert(svg.includes('percentage change'));assert(svg.includes('mp-zero'));
const flat=prices.svg([{name:'Flat',points:[['2026-11-02',0],['2026-11-03',0]]}],[],[],{percent:true});
assert(!flat.includes('NaN')&&!flat.includes('Infinity'),'flat zero-return chart has a finite axis');
assert(fs.readFileSync('site/earnings-desk.js','utf8').includes("earnings:true,period:'6M'"));
assert(fs.readFileSync('site/v4.html','utf8').includes('share-chart-workbench.js'));
const mixed={kind:'equity',sharedClose:true,value:120,date:'2026-11-13',dailyPoints:[['2026-11-12',100],['2026-11-13',120]],points:[['2024-11-10',60],['2026-11-12',100],['2026-11-13',120]]};
assert(Math.abs(snapshot.comparison(mixed,'days',1).percent-20)<1e-9,'daily comparisons use actual daily closes');
assert(snapshot.comparison(mixed,'days',2).reason,'older weekly labels cannot impersonate daily sessions');
assert.equal(snapshot.comparison(mixed,'years',2).percent,100);
assert.match(snapshot.comparison(mixed,'years',2).basis,/period label/);
console.log('Multi-share common-date normalization, calendar earnings markers, six series and empty/flat chart checks passed.');
