const assert=require('node:assert/strict');
const api=require('../site/company-context.js');
const news=(id,date,tickers=['AAPL'],extra={})=>({id,title:'Story '+id,href:'https://example.com/story/'+id,published_at:date,tickers,...extra});
assert.deepEqual(api.routes('AAPL'),{earnings:'v4.html?company=AAPL#earnings',shares:'v4.html?company=AAPL#history/shares',si:'v4.html?company=AAPL#history/si',watchlist:'v4.html?company=AAPL#watchlist'});
assert.equal(api.routes('BRK-B').shares,'v4.html?company=BRK.B#history/shares');
assert.equal(api.routes('<script>'),null);
const rows=Array.from({length:14},(_,i)=>news(String(i),'2026-11-'+String(i+1).padStart(2,'0')));
rows.push(news('wrong','2026-11-15',['MSFT']),news('future','2030-01-01'),news('missing',null),news('unsafe','2026-11-15',['AAPL'],{href:'javascript:alert(1)'}),{...rows[13],id:'duplicate',href:rows[13].href+'#fragment'});
const selected=api.newsFor(rows,'AAPL',Date.parse('2026-11-16T00:00:00Z'));
assert.equal(selected.length,10);
assert.equal(selected[0].id,'13');
assert.equal(selected[9].id,'4');
assert.equal(selected.some(n=>['wrong','future','missing','unsafe','duplicate'].includes(n.id)),false);
assert.equal(api.newsFor([news('b','2026-11-01',['BRK-B'])],'BRK.B',Date.parse('2026-11-16')).length,1);
const records=[{id:'wrong',bbTicker:'AAPL US',currency:'EUR'},{id:'right',bbTicker:'AAPL US',currency:'USD',compareEligible:true},{id:'brk',bbTicker:'BRK/B US',currency:'USD'}];
assert.equal(api.listing(records,'AAPL').id,'right');
assert.equal(api.listing(records,'BRK.B').id,'brk');
assert.equal(api.listing([...records,{id:'ambiguous',bbTicker:'AAPL US',currency:'USD'}],'AAPL'),null);
const points=[{date:'2026-11-02',value:22,source:'A',basis:'forward'},{date:'2026-11-04',value:0},{date:'2026-11-05',value:-2},{date:'2026-11-10',value:24,source:'B',basis:'trailing'},{date:'2026-02-30',value:99}];
assert.equal(api.prior(points,'2026-11-01','pe'),null);
assert.equal(api.prior(points,'2026-11-06','pe').date,'2026-11-02');
assert.equal(api.usable(points,'pe').length,2);
assert.equal(api.seriesGroups(api.usable(points,'pe')).length,2);
const events=api.eventsFor([{date:'2026-11-02',label:'Q4',source:{url:'https://example.com/release'}}],[news('n','2026-11-10',['AAPL'])],'AAPL');
assert.equal(events.length,2);
assert.equal(events[0].timing,'date_only');
const metrics={price:[{date:'2026-11-01',value:100,source:'Price',currency:'USD'}],pe:points,pb:[]};
assert.deepEqual(api.periodWindow(metrics,events,'All'),{from:'2026-11-01',to:'2026-11-10'});
const svg=api.chart(metrics,events,{from:'2026-11-01',to:'2026-11-10'},events[0].date,'USD');
assert.match(svg,/P\/E/);assert.match(svg,/P\/B/);assert.match(svg,/cc-event-selected/);assert.doesNotMatch(svg,/NaN|Infinity/);
assert.match(api.eventValues(events[0],metrics),/Latest available observation on or before/);
assert.match(api.eventValues(events[0],metrics),/not proof of causation/);
assert.equal(api.chart({},[],null,null,'USD').includes('No dated observations'),true);
const injected=api.chart({price:[],pe:[{date:'2026-11-01',value:12,source:'<img src=x>'}],pb:[]},[],{from:'2026-11-01',to:'2026-11-01'},null,'USD');
assert.doesNotMatch(injected,/<img src=x>/);assert.match(injected,/&lt;img/);
console.log('PASS company routes, news matching/deduplication, exact listing resolution, sparse valuation observations, shared timeline and escaping');
